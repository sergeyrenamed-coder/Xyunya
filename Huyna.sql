/* 1. Студенты, обучающиеся на факультете "ит" */
SELECT DISTINCT
    С.Фамилия,
    П.Направление,
    К.Название AS Кафедра
FROM Студент С
JOIN Специальность П ON С.Номер = П.Номер
JOIN Кафедра К ON П.Шифр = К.Шифр
WHERE К.Факультет = 'ит';
GO

/* 2. Выпускающие кафедры */
SELECT DISTINCT
    Ф.Название AS Факультет,
    К.Шифр,
    К.Название AS Кафедра,
    С.Фамилия AS Заведующий
FROM Факультеты Ф
JOIN Кафедра К ON Ф.Аббревиатура = К.Факультет
JOIN Специальность П ON П.Шифр = К.Шифр
JOIN Сотрудник С ON С.Таб_номер = К.Заведующий
ORDER BY Ф.Название, К.Шифр;
GO

/* 3. Непосредственный руководитель каждого сотрудника */
SELECT
    С.Таб_номер,
    С.Фамилия,
    ISNULL(Р.Фамилия, N'') AS Руководитель
FROM Сотрудник С
LEFT JOIN Сотрудник Р ON С.Шеф = Р.Таб_номер
ORDER BY С.Таб_номер;
GO

/* 4. Студенты, сдавшие минимум два экзамена */
SELECT
    С.Фамилия,
    COUNT(*) AS Количество_экзаменов
FROM Студент С
JOIN Экзамен Э ON С.Рег_номер = Э.Рег_номер
GROUP BY С.Фамилия
HAVING COUNT(*) >= 2;
GO

/* 5. Инженеры с зарплатой меньше 20000 */
SELECT
    Фамилия,
    Должность,
    Зарплата
FROM Сотрудник
WHERE Должность LIKE N'%инженер%'
  AND Зарплата < 20000;
GO

/* 6. Студенты, сдавшие экзамены в заданной аудитории */
DECLARE @Аудитория NVARCHAR(20) = N'А-101';

SELECT DISTINCT
    С.Фамилия,
    Д.Название AS Дисциплина,
    Э.Дата,
    Э.Аудитория
FROM Студент С
JOIN Экзамен Э ON С.Рег_номер = Э.Рег_номер
JOIN Дисциплина Д ON Э.Код = Д.Код
WHERE Э.Аудитория = @Аудитория
ORDER BY С.Фамилия, Э.Дата;
GO

/* 7. Учетный номер, фамилия, количество экзаменов и средний балл, если средний >= 4 */
SELECT
    С.Рег_номер,
    С.Фамилия,
    COUNT(Э.ID) AS Количество_экзаменов,
    AVG(CAST(Э.Оценка AS DECIMAL(10,2))) AS Средний_балл
FROM Студент С
JOIN Экзамен Э ON С.Рег_номер = Э.Рег_номер
GROUP BY С.Рег_номер, С.Фамилия
HAVING AVG(CAST(Э.Оценка AS DECIMAL(10,2))) >= 4
ORDER BY С.Рег_номер;
GO

/* 8. Заведующие кафедрами, зарплата и степень */
SELECT
    С.Фамилия,
    С.Зарплата,
    П.Степень
FROM Кафедра К
JOIN Сотрудник С ON К.Заведующий = С.Таб_номер
JOIN Преподаватель П ON С.Таб_номер = П.Таб_номер
ORDER BY С.Фамилия;
GO

/* 9. Список профессоров */
SELECT
    С.Фамилия,
    П.Степень
FROM Сотрудник С
JOIN Преподаватель П ON С.Таб_номер = П.Таб_номер
WHERE С.Должность = N'профессор';
GO

/* 10. Дисциплина, фамилия, должность, степень, дата и аудитория в интервале дат */
DECLARE @Дата_от DATE = '2026-05-10';
DECLARE @Дата_до DATE = '2026-05-20';

SELECT DISTINCT
    Д.Название AS Дисциплина,
    С.Фамилия,
    С.Должность,
    П.Степень,
    Э.Дата,
    Э.Аудитория
FROM Экзамен Э
JOIN Дисциплина Д ON Э.Код = Д.Код
JOIN Сотрудник С ON Э.Таб_номер = С.Таб_номер
JOIN Преподаватель П ON Э.Таб_номер = П.Таб_номер
WHERE Э.Дата BETWEEN @Дата_от AND @Дата_до
ORDER BY Э.Дата, Д.Название;
GO

/* 11. Преподаватели, принявшие более трех экзаменов */
SELECT
    С.Фамилия,
    COUNT(*) AS Количество_экзаменов
FROM Экзамен Э
JOIN Сотрудник С ON Э.Таб_номер = С.Таб_номер
GROUP BY С.Фамилия
HAVING COUNT(*) > 3
ORDER BY Количество_экзаменов DESC;
GO

/* 12. Студенты, не сдавшие ни одного экзамена в указанную дату */
DECLARE @Дата_экзамена DATE = '2026-05-10';

SELECT
    С.Рег_номер,
    С.Фамилия
FROM Студент С
LEFT JOIN Экзамен Э
    ON С.Рег_номер = Э.Рег_номер
   AND Э.Дата = @Дата_экзамена
WHERE Э.Рег_номер IS NULL
ORDER BY С.Рег_номер;
GO
