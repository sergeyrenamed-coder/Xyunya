CREATE TABLE Факультеты
(
    Аббревиатура VARCHAR(10) PRIMARY KEY,
    Название NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Кафедра
(
    Шифр VARCHAR(10) PRIMARY KEY,
    Факультет VARCHAR(10) NOT NULL,
    Название NVARCHAR(100) NOT NULL,
    Заведующий INT NULL
);
GO

CREATE TABLE Специальность
(
    Номер INT PRIMARY KEY,
    Шифр VARCHAR(10) NOT NULL,
    Направление NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Студент
(
    Рег_номер INT PRIMARY KEY,
    Фамилия NVARCHAR(50) NOT NULL,
    Номер INT NOT NULL
);
GO

CREATE TABLE Сотрудник
(
    Таб_номер INT PRIMARY KEY,
    Фамилия NVARCHAR(50) NOT NULL,
    Должность NVARCHAR(50) NOT NULL,
    Зарплата DECIMAL(10,2) NOT NULL,
    Шифр VARCHAR(10) NOT NULL,
    Шеф INT NULL
);
GO

CREATE TABLE Преподаватель
(
    Таб_номер INT PRIMARY KEY,
    Степень NVARCHAR(50) NOT NULL
);
GO

CREATE TABLE Дисциплина
(
    Код INT PRIMARY KEY,
    Название NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE Экзамен
(
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Рег_номер INT NOT NULL,
    Таб_номер INT NOT NULL,
    Код INT NOT NULL,
    Оценка INT NOT NULL,
    Дата DATE NOT NULL,
    Аудитория NVARCHAR(20) NOT NULL
);
GO

